// Explicitly sync brand assets only. No environment files or journal data are read.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const destination = process.argv.slice(2).find((value) => value !== "--check");
const website = path.resolve(
  destination ?? path.join(root, "../myshotlog-website"),
);
const design = JSON.parse(
  await readFile(path.join(root, "lib/brand/design.json"), "utf8"),
);
const c = design.colours;
const vars = {
  bg: c.background,
  ink: c.ink,
  muted: c.muted,
  line: c.line,
  green: c.green,
  pale: c.pale,
  "green-light": "var(--pale)",
  gold: c.gold,
  surface: c.surface,
  white: c.white,
  danger: c.danger,
  "medal-gold": c.medalGold,
  "medal-silver": c.medalSilver,
  "medal-bronze": c.medalBronze,
  "radius-control": design.radius.control + "px",
  "radius-panel": design.radius.panel + "px",
  "radius-overlay": design.radius.overlay + "px",
  "weight-body": design.weight.body,
  "weight-heading": design.weight.heading,
  "weight-emphasis": design.weight.emphasis,
};
const css = `/* Generated by scripts/sync-brand.mjs in the MyShotLog app. */\n:root {\n${Object.entries(
  vars,
)
  .map(([key, value]) => `  --${key}: ${value};`)
  .join(
    "\n",
  )}\n  font-family: var(${design.font.variable}), Arial, sans-serif;\n  color: var(--ink);\n  background: var(--bg);\n}\nbody {\n  font-weight: var(--weight-body);\n}\nh1,\nh2,\nh3,\nh4 {\n  font-weight: var(--weight-heading);\n}\nstrong {\n  font-weight: var(--weight-emphasis);\n}\n`;
const assets = [
  "app/favicon.ico",
  `lib/fonts/${design.font.file}`,
  `lib/fonts/${design.font.webFile}`,
  "lib/fonts/OFL.txt",
  ...[
    "MyShotLog-logo.svg",
    "MyShotLog-logo.png",
    "MyShotLog-icon.svg",
    "MyShotLog-icon.png",
    "MyShotLog-logo-monochrome.svg",
    "MyShotLog-logo-monochrome.png",
    "MyShotLog-apple-touch-icon.png",
    "MyShotLog-preview.png",
  ].map((name) => "public/brand/" + name),
];
const failures = [];
async function apply(target, bytes, label) {
  if (check) {
    const actual = await readFile(target).catch(() => undefined);
    if (!actual || !actual.equals(Buffer.from(bytes))) failures.push(label);
  } else {
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, bytes);
  }
}
await apply(path.join(root, "app/brand.css"), css, "app theme");
await apply(path.join(website, "app/brand.css"), css, "website theme");
for (const asset of assets)
  await apply(
    path.join(website, asset),
    await readFile(path.join(root, asset)),
    "website " + asset,
  );
if (failures.length) {
  console.error("Brand differences:\n" + failures.join("\n"));
  process.exitCode = 1;
} else
  console.log(
    check
      ? "Brand themes, fonts, logos and favicons match."
      : "Brand themes and public website assets synchronized.",
  );
